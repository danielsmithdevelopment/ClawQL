/**
 * Build-time TOC map for docs Layout / SectionProvider.
 * Workers-safe: no runtime filesystem. Runs after sync-* scripts in prebuild/dev.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import glob from 'fast-glob'

import {
  extractH2Sections,
  TOC_MIN_SECTIONS,
} from './lib/extract-h2-sections.mjs'
import { GENERATED_BODY_ROUTES } from './lib/generated-doc-routes.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const websiteRoot = path.resolve(__dirname, '..')
const appDir = path.join(websiteRoot, 'src/app')
const generatedDir = path.join(websiteRoot, 'src/generated')
const trainingDir = path.join(generatedDir, 'security-training/bodies')
const pluginsDir = path.join(generatedDir, 'clawql-plugins/bodies')
const outFile = path.join(
  websiteRoot,
  'src/generated/doc-layout-sections.generated.ts',
)

/**
 * @type {Map<string, { title: string, id: string }[]>}
 */
const byPath = new Map()

/**
 * @param {string} url
 * @param {{ title: string, id: string }[]} sections
 */
function mergePath(url, sections) {
  if (!url || url.includes('#')) return
  const normalized = url === '/' ? '/' : url.replace(/\/$/, '') || '/'
  if (sections.length < TOC_MIN_SECTIONS) return
  const existing = byPath.get(normalized) ?? []
  const seen = new Set(existing.map((s) => s.id))
  const merged = [...existing]
  for (const s of sections) {
    if (seen.has(s.id)) continue
    seen.add(s.id)
    merged.push(s)
  }
  if (merged.length >= TOC_MIN_SECTIONS) {
    byPath.set(normalized, merged)
  }
}

// Hand-written App Router MDX pages
for (const file of glob.sync('**/page.mdx', { cwd: appDir })) {
  const url = '/' + file.replace(/(^|\/)page\.mdx$/, '').replace(/\/$/, '')
  const mdx = fs.readFileSync(path.join(appDir, file), 'utf8')
  mergePath(url === '/' ? '/' : url || '/', extractH2Sections(mdx))
}

// Home body (page.tsx imports home-body.mdx)
const homeBody = path.join(appDir, 'home-body.mdx')
if (fs.existsSync(homeBody)) {
  mergePath('/', extractH2Sections(fs.readFileSync(homeBody, 'utf8')))
}

// Generated long-form docs
for (const [fileName, url] of Object.entries(GENERATED_BODY_ROUTES)) {
  const filePath = path.join(generatedDir, fileName)
  if (!fs.existsSync(filePath)) continue
  mergePath(url, extractH2Sections(fs.readFileSync(filePath, 'utf8')))
}

// Plugin pages
if (fs.existsSync(pluginsDir)) {
  for (const fileName of glob.sync('*.mdx', { cwd: pluginsDir })) {
    const slug = fileName.replace(/\.mdx$/, '')
    const mdx = fs.readFileSync(path.join(pluginsDir, fileName), 'utf8')
    mergePath(`/plugins/${slug}`, extractH2Sections(mdx))
  }
}

// Security training modules
if (fs.existsSync(trainingDir)) {
  for (const fileName of glob.sync('*.mdx', { cwd: trainingDir })) {
    const slug = fileName.replace(/\.mdx$/, '')
    const mdx = fs.readFileSync(path.join(trainingDir, fileName), 'utf8')
    mergePath(`/security/best-practices/${slug}`, extractH2Sections(mdx))
  }
}

const paths = [...byPath.keys()].sort((a, b) => a.localeCompare(b))

const lines = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by scripts/generate-doc-layout-sections.mjs — do not edit.',
  "import type { Section } from '@/components/SectionProvider'",
  '',
  'export const DOC_LAYOUT_SECTIONS_BY_PATH: Record<string, Array<Section>> = {',
]

for (const url of paths) {
  const sections = byPath.get(url)
  lines.push(`  ${JSON.stringify(url)}: [`)
  for (const s of sections) {
    lines.push(
      `    { title: ${JSON.stringify(s.title)}, id: ${JSON.stringify(s.id)} },`,
    )
  }
  lines.push('  ],')
}

lines.push('}', '')

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, lines.join('\n'), 'utf8')

console.log(
  `generate-doc-layout-sections: ${paths.length} routes with ≥${TOC_MIN_SECTIONS} h2s → ${path.relative(websiteRoot, outFile)}`,
)
