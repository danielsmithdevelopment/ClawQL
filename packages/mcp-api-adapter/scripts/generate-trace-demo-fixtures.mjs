#!/usr/bin/env node
/**
 * Generate demo trace fixtures with real cl100k_base token counts (GPT-4/o family).
 * Run: node scripts/generate-trace-demo-fixtures.mjs
 * Output: src/fixtures/trace-demo-fixtures.generated.ts
 */
import { getEncoding } from "js-tiktoken";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const enc = getEncoding("cl100k_base");
const __dirname = dirname(fileURLToPath(import.meta.url));

/** @see OpenAI cookbook — chat message overhead for gpt-4/cl100k_base */
function countChatMessages(messages) {
  let n = 0;
  for (const msg of messages) {
    n += 3; // tokens per message
    n += enc.encode(msg.content).length;
    if (msg.name) n += 1;
  }
  n += 3; // assistant reply priming
  return n;
}

function countText(text) {
  return enc.encode(text).length;
}

function buildDemoMessages(toolMsg) {
  return [
    {
      role: "system",
      content:
        "You are ClawQL harness. Prefer search() then execute(). Keep tool results compact.",
    },
    {
      role: "system",
      content:
        "Obsidian vault system-seed memory: [[MCP UI ClawQL Demo]] agent.md notes for this session.",
    },
    {
      role: "user",
      content: "List GitHub repos then summarize the first one.",
    },
    {
      role: "user",
      content: JSON.stringify({
        name: "search",
        inputSchema: { type: "object", properties: { query: { type: "string" } } },
      }),
    },
    toolMsg,
  ];
}

const compressedResult = {
  role: "tool",
  content: JSON.stringify({
    results: [{ id: "repos.list", method: "GET", path: "/user/repos", score: 12 }],
  }),
};

const fatResult = {
  role: "tool",
  content: JSON.stringify({
    results: Array.from({ length: 40 }, (_, i) => ({
      id: `repos.list.${i}`,
      method: "GET",
      path: "/user/repos",
      full: "x".repeat(800),
      description: "Untrimmed OpenAPI dump ".repeat(20),
    })),
  }),
};

const response = "First repo looks active; next hop is execute(repos.get).";
const base = new Date("2026-08-26T12:00:00.000Z").getTime();

function perMessageTokens(messages) {
  return messages.map((msg) => {
    let t = 3 + enc.encode(msg.content).length;
    if (msg.name) t += 1;
    return t;
  });
}

function mkRecord(id, offsetMs, messages) {
  const inputTokens = countChatMessages(messages);
  const outputTokens = countText(response);
  const messageTokens = perMessageTokens(messages);
  return {
    id,
    correlationId: "SESSION",
    timestamp: new Date(base + offsetMs).toISOString(),
    modelId: "demo/gpt-4o",
    provider: "demo",
    messages: messages.map((m, i) => ({ ...m, tokens: messageTokens[i] })),
    response,
    usage: { inputTokens, outputTokens },
    latencyMs: 120 + offsetMs / 10,
  };
}

function buildSession(sessionId, toolMsg, isFat) {
  const turn1Messages = buildDemoMessages(toolMsg);
  const turn1 = mkRecord(isFat ? "f1" : "c1", 0, turn1Messages);

  const assistantTurn1 = { role: "assistant", content: response };
  const turn2Full = [
    ...turn1Messages,
    assistantTurn1,
    turn1Messages[2],
    turn1Messages[3],
    toolMsg,
  ];
  const turn2 = mkRecord(isFat ? "f2" : "c2", 30_000, turn2Full);

  for (const rec of [turn1, turn2]) {
    rec.correlationId = sessionId;
    delete rec.contextInputTokens;
  }
  return [turn1, turn2];
}

const compressed = buildSession("demo-compressed", compressedResult, false);
const fat = buildSession("demo-fat", fatResult, true);

const meta = {
  encoding: "cl100k_base",
  method: "openai-chat-message-overhead",
  generatedAt: new Date().toISOString(),
  note: "Per-message tokens include 3-token chat overhead each; turn 2 inputTokens count full prior context + new messages.",
};

const out = `/** AUTO-GENERATED by scripts/generate-trace-demo-fixtures.mjs — do not edit */
import type { TraceCallRecord } from "../mcp-ui-trace.js";

export const TRACE_DEMO_TOKENIZATION = ${JSON.stringify(meta, null, 2)} as const;

export const TRACE_DEMO_COMPRESSED: TraceCallRecord[] = ${JSON.stringify(compressed, null, 2)};

export const TRACE_DEMO_FAT: TraceCallRecord[] = ${JSON.stringify(fat, null, 2)};
`;

const outPath = join(__dirname, "../src/fixtures/trace-demo-fixtures.generated.ts");
writeFileSync(outPath, out, "utf8");

console.log("Wrote", outPath);
for (const [label, records] of [
  ["compressed", compressed],
  ["fat", fat],
]) {
  const inTok = records.reduce((s, r) => s + r.usage.inputTokens, 0);
  const outTok = records.reduce((s, r) => s + r.usage.outputTokens, 0);
  console.log(`${label}: input=${inTok} output=${outTok} (cl100k_base)`);
}
